-- Raw layer objects used by ingest/load_raw.py.
-- Matches MSV_DWH_DEV.VN_MMS_RAW_STOCK as of 2026-11-06.
--
-- Run in Snowsight once per environment. For prod, change the USE SCHEMA line.
-- Safe to re-run: IF NOT EXISTS never replaces an object or its data, and also
-- does not apply later edits to an existing object (use ALTER for those).
--
-- Requires the database, schema and role from Step 2 of the migration guide.

USE ROLE DWH_TRANSFORMER;
USE SCHEMA MSV_DWH_DEV.VN_MMS_RAW_STOCK;

-- File format and internal stage
CREATE FILE FORMAT IF NOT EXISTS CSV_RAW
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  ENCODING = 'UTF8'
  ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
  EMPTY_FIELD_AS_NULL = FALSE;

CREATE STAGE IF NOT EXISTS MMS_STAGE
  DIRECTORY = (ENABLE = TRUE);

